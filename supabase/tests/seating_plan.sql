-- Run as database owner after migrations. Test data and password settings roll back.
begin;
update private.dashboard_settings set password_hash = extensions.crypt('seating-test-password', extensions.gen_salt('bf')) where id;
do $$
declare
  test_password text := 'seating-test-password'; suffix text := gen_random_uuid()::text;
  first_table bigint; second_table bigint; family bigint; first_guest bigint; second_guest bigint;
  first_token uuid; second_token uuid; guest_key text; companion_key text;
  snapshot jsonb; answers jsonb; failed boolean;
begin
  perform public.dashboard_add_guest(test_password, 'Seating ' || suffix, 'First ' || suffix);
  select g.id, g.family_id, i.token into first_guest, family, first_token from public.guests g join public.invitations i on i.family_id = g.family_id where g.guest_name = 'First ' || suffix;
  perform public.dashboard_add_guest(test_password, '', 'Second ' || suffix, family);
  select g.id, i.token into second_guest, second_token from public.guests g join public.invitations i on i.family_id = g.family_id where g.guest_name = 'Second ' || suffix;
  guest_key := 'guest:' || first_guest;
  companion_key := 'companion:' || family;
  first_table := public.dashboard_save_table(test_password, 'Tavolo A ' || suffix, 2);
  second_table := public.dashboard_save_table(test_password, 'Tavolo B ' || suffix, 4);
  perform public.dashboard_assign_seat(test_password, guest_key, first_table, 2);
  snapshot := public.dashboard_seating_plan(test_password);
  if not exists (select 1 from jsonb_array_elements(snapshot->'people') p where p->>'key' = guest_key and p->>'attending' is null and (p->>'seat_number')::integer = 2) then raise exception 'Pending guest or seat missing'; end if;
  failed := false;
  begin perform public.dashboard_assign_seat(test_password, 'guest:' || second_guest, first_table, 2);
  exception when sqlstate '22023' then failed := true; end;
  if not failed then raise exception 'Occupied seat accepted'; end if;
  failed := false;
  begin perform public.dashboard_save_table(test_password, 'Too small', 1, first_table);
  exception when sqlstate '22023' then failed := true; end;
  if not failed then raise exception 'Occupied seat removed by capacity change'; end if;
  failed := false;
  begin perform public.dashboard_assign_seat(test_password, guest_key, first_table, 3);
  exception when sqlstate '22023' then failed := true; end;
  if not failed then raise exception 'Out of capacity seat accepted'; end if;
  perform public.dashboard_assign_seat(test_password, guest_key, second_table, 1);
  if (select count(*) from public.seating_assignments where guest_id = first_guest) <> 1 then raise exception 'Guest assigned twice'; end if;
  if exists (select 1 from public.seating_assignments where table_id = first_table and seat_number = 2) then raise exception 'Old seat not freed'; end if;
  perform public.dashboard_move_table(test_password, second_table, 400, 300);
  perform public.dashboard_save_table(test_password, 'Renamed ' || suffix, 6, second_table);
  if not exists (select 1 from public.seating_tables where id = second_table and x = 400 and y = 300 and capacity = 6 and name = 'Renamed ' || suffix) then raise exception 'Table edits not saved'; end if;
  perform public.dashboard_set_family_plus_one(test_password, family, true);
  answers := jsonb_build_array(jsonb_build_object('guest_id', first_guest, 'attending', true), jsonb_build_object('guest_id', second_guest, 'attending', false));
  perform public.submit_family_response(first_token, '', answers, null, 'Companion ' || suffix);
  perform public.dashboard_assign_seat(test_password, companion_key, second_table, 2);
  snapshot := public.dashboard_seating_plan(test_password);
  if not exists (select 1 from jsonb_array_elements(snapshot->'people') p where p->>'key' = guest_key and p->'attending' = 'true'::jsonb) then raise exception 'Confirmed status missing'; end if;
  if not exists (select 1 from jsonb_array_elements(snapshot->'people') p where p->>'key' = 'guest:' || second_guest and p->'attending' = 'false'::jsonb) then raise exception 'Declined status missing'; end if;
  if (select count(*) from jsonb_array_elements(snapshot->'people') p where p->>'key' = companion_key) <> 1 then raise exception 'Companion duplicated'; end if;
  perform public.dashboard_archive_table(test_password, second_table, true);
  failed := false;
  begin perform public.dashboard_assign_seat(test_password, guest_key, second_table, 3);
  exception when sqlstate '22023' then failed := true; end;
  if not failed then raise exception 'Archived table accepted'; end if;
  perform public.dashboard_archive_table(test_password, second_table, false);
  if (select count(*) from public.seating_assignments where table_id = second_table) <> 2 then raise exception 'Archive lost assignments'; end if;
  perform public.dashboard_assign_seat(test_password, guest_key);
  if exists (select 1 from public.seating_assignments where guest_id = first_guest) then raise exception 'Unassign failed'; end if;
  perform public.dashboard_set_family_plus_one(test_password, family, false);
  if exists (select 1 from public.seating_assignments where companion_family_id = family) then raise exception 'Removed companion still seated'; end if;
  failed := false;
  begin perform public.dashboard_seating_plan('wrong-password');
  exception when sqlstate '28000' then failed := true; end;
  if not failed then raise exception 'Unauthenticated read allowed'; end if;
  failed := false;
  begin perform public.dashboard_assign_seat('wrong-password', guest_key, first_table, 1);
  exception when sqlstate '28000' then failed := true; end;
  if not failed then raise exception 'Unauthenticated write allowed'; end if;
  if has_table_privilege('anon', 'public.seating_tables', 'SELECT') or has_table_privilege('anon', 'public.seating_assignments', 'INSERT') then raise exception 'Public table access allowed'; end if;
end $$;
rollback;
